"""RWKV-7 chain speculative decoding on sglang spec-V2 (ADR-0006, Strategy B).

A small RWKV-7 *draft* proposes tokens by running greedy decode steps on its
own recurrent state; the *target* verifies them in ONE ``TARGET_VERIFY``
forward, reusing upstream's generic spec-v2 verify+commit machinery (the same
``NgramVerifyInput`` / ``eagle_sample`` / ``commit_mamba_states_after_verify``
path ``NGRAMWorker`` uses) instead of a bespoke hand-rolled verify. The only
genuinely new logic this worker owns is the *draft's own* recurrent-state
rollback (upstream's commit machinery only knows about the target).

Why not subclass ``EAGLEWorkerV2`` / ``StandaloneWorkerV2``: their draft path is
transformer-shaped (draft attention backend, draft cuda-graphs, tree mask) — a
recurrent RWKV draft has no attention or KV, so it cannot ride that machinery.
Instead we mirror ``NGRAMWorker`` (subclass ``BaseSpecWorker`` directly, build a
verify input from a non-EAGLE draft source, reuse the target verify), with the
draft source being a real 0.1B RWKV model instead of an n-gram corpus.

Chain shape (topk=1, verified against ``verify_tree_greedy_kernel_triton``,
NOT guessed): the verify window is ``K = speculative_num_draft_tokens``
positions, but position 0 is *not* a new guess — the greedy-tree-walk kernel
unconditionally accepts node 0 as the walk's root (mirrors EAGLE's "the first
token generated by the target model... is always accepted from the previous
iteration"). So position 0 must be ``t_last`` (the last already-committed
token, re-fed so the target emits a prediction for what follows it), and the
draft only needs to produce ``K-1`` genuine new guesses at positions 1..K-1:
    candidates = [t_last, d_0, d_1, ..., d_{K-2}]
target_predict[j] validates candidates[j+1]; target_predict[K-1] (after the
last real draft) is never checked against anything and becomes the bonus
token if the whole chain accepts. ``eagle_sample`` returns
``accept_lens = num_correct_drafts + 1`` (the "+1" is that free position-0
accept, NOT a bonus beyond the drafts — the real per-request draft accept
count is ``accept_lens - 1``, ranging 0..K-1).

RWKV-7's own linear-attention backend (``rwkv7_backend.py``) needed a small
addition to make the "reuse upstream verify" premise true: unlike
GDN/KDA/Lightning, RWKV bypasses the generic ``AttentionBackend.forward_extend``
dispatch entirely (the model calls ``token_shift``/``recurrence`` directly), so
none of the existing ``is_target_verify`` capture code applied. Fixed by adding
an ``is_target_verify`` branch there: K sequential calls to the same in-place
decode-shaped kernel used by plain decode, capturing each step's state into
``intermediate_ssm``/``intermediate_conv_window`` for the (already-generic)
``commit_mamba_states_after_verify`` to select from afterward.

Exact-by-construction at temperature 0: only tokens the target would greedily
emit are committed. Registered as the plugin algorithm ``RWKV_SPEC``; run with
``--disable-overlap-schedule`` (the recurrent verify is a synchronous V2 path).

Status: Strategy B build, iterated on the tower main container. The earlier
self-contained "Strategy A" implementation (manual snapshot/restore + a
re-run-the-accepted-prefix commit, no upstream verify reuse) is kept below,
renamed and unwired, as a fallback reference in case the backend addition
above hits a wall — see the block comment before it.

Speed (ADR-0006 (ii)): the draft's own K-1 step decode loop now runs through
a hand-rolled, self-contained CUDA graph (see the "draft decode CUDA graph"
section below), NOT sglang's shared ``DecodeCudaGraphRunner`` -- that class
hardcodes ``capture_forward_mode=TARGET_VERIFY`` for any draft worker under
any speculative algorithm (an EAGLE-family assumption incompatible with a
plain recurrent per-step draft) and is deliberately left untouched (shared,
high-blast-radius file). The custom graph lives entirely in this file, is
built lazily on first use, and falls back to the pre-existing eager path
(unchanged) on any capture failure or via ``RWKV_SPEC_DRAFT_GRAPH=0``.
"""

